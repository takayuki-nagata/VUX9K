"""
SD card transcripts (sim/sd_transcripts/*.txt): byte-level MOSI/CS -> MISO exchanges
of firmware-like host sequences, recorded from the RTL tests' card
(sim/integration/sdcard_protocol.py). This test re-records every scenario and
compares with the committed file; emu/crates/vux9k_emu/tests/sd_transcripts.rs
replays the same files through the emulator's card. Together they keep the two
cards identical at byte level.

After an intended change of the Python card: SD_TRANSCRIPTS_UPDATE=1 pytest this
file, review the diff, and make the Rust card match.

File format, one record per line ('#' comments):
  card sdhc=0|1 strict=0|1 [mute=N,N] [bad=LBA,LBA] [never_ready] [read_error] [write_reject]
  sector LBA HEX             preloaded sector
  cs 0|1                     CS change (1 = selected)
  sclk HZ                    SCLK of the bytes that follow (default 400 kHz)
  x 0|1 MOSI-HEX MISO-HEX    bytes clocked with CS at that level, and the answers
  expect-sector LBA HEX
  expect-commands CMD:ARG,...
  expect-violations N
  expect-idle-clocks N
"""

import os
import sys

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO_ROOT, "sim", "integration"))
from sdcard_protocol import SECTOR, SdCardProtocol, crc7, crc16  # noqa: E402

DIR = os.path.join(REPO_ROOT, "sim", "sd_transcripts")


class Recorder:
    """Host side, as the firmware drives the SPI master (transfer/set_cs/send_cmd)."""

    def __init__(self, name, **card):
        self.card = SdCardProtocol(**card)
        opts = [f"sdhc={int(self.card.sdhc)}", f"strict={int(self.card.strict)}"]
        if card.get("mute_cmds"):
            opts.append("mute=" + ",".join(str(c) for c in card["mute_cmds"]))
        if card.get("bad_sectors"):
            opts.append("bad=" + ",".join(str(c) for c in card["bad_sectors"]))
        opts += [f for f in ("never_ready", "read_error", "write_reject") if card.get(f)]
        self.lines = [f"# {name}: generated by sim/emu/test_sd_transcripts.py", "card " + " ".join(opts)]
        self.selected = False
        self._run = None  # [sel, mosi bytearray, miso bytearray]

    def _flush(self):
        if self._run:
            sel, mosi, miso = self._run
            self.lines.append(f"x {int(sel)} {mosi.hex()} {miso.hex()}")
            self._run = None

    def sector(self, lba, data):
        self.card.set_sector(lba, data)
        self.lines.append(f"sector {lba} {self.card.get_sector(lba).hex()}")

    def cs(self, selected):
        self._flush()
        if selected != self.selected:
            self.selected = selected
            self.card.set_cs(selected)
            self.lines.append(f"cs {int(selected)}")

    def sclk(self, hz):
        self._flush()
        self.card.set_sclk_hz(hz)
        self.lines.append(f"sclk {hz}")

    def xfer(self, b):
        if self._run is None or self._run[0] != self.selected:
            self._flush()
            self._run = [self.selected, bytearray(), bytearray()]
        m = self.card.exchange(b, self.selected)
        self._run[1].append(b)
        self._run[2].append(m)
        return m

    def cmd(self, cmd, arg, crc=0x95):
        self.cs(True)
        for b in bytes([0x40 | cmd]) + arg.to_bytes(4, "big") + bytes([crc]):
            self.xfer(b)
        for _ in range(200):
            r = self.xfer(0xFF)
            if r != 0xFF:
                return r
        return 0xFF

    def cmd_crc(self, cmd, arg):
        """A command with its real CRC7, as Linux's mmc_spi sends every command."""
        frame = bytes([0x40 | cmd]) + arg.to_bytes(4, "big")
        return self.cmd(cmd, arg, crc7(frame) << 1 | 1)

    def data(self, n):
        """A data block after the R1 (mmc_spi's token search): token, n bytes, CRC16."""
        for _ in range(8):
            if self.xfer(0xFF) == 0xFE:
                break
        else:
            return None
        data = self.read(n)
        crc = self.read(2)
        assert int.from_bytes(crc, "big") == crc16(data), "data CRC16"
        return data

    def write_blocks(self, token, blocks, crc_ok=True):
        """mmc_spi's block writes after CMD24/CMD25: one FF, the token, the block, its
        CRC16, then four bytes of status (the data response and the busy bytes)."""
        resps = []
        for data in blocks:
            self.xfer(0xFF)
            self.xfer(token)
            for b in data:
                self.xfer(b)
            crc = crc16(data) ^ (0 if crc_ok else 1)
            self.xfer(crc >> 8)
            self.xfer(crc & 0xFF)
            resps.append(self.read(4))
        return resps

    def deselect(self):
        self.cs(False)
        self.xfer(0xFF)

    def read(self, n):
        return bytes(self.xfer(0xFF) for _ in range(n))

    def init(self):
        """fw_drivers' SdCard::init() (the first stage's)."""
        self.deselect()
        for _ in range(16):
            self.xfer(0xFF)
        self.cmd(0, 0)
        self.deselect()
        if self.cmd(8, 0x1AA, 0x87) == 0x01:
            self.read(4)
        self.deselect()
        for _ in range(3):
            r55 = self.cmd(55, 0, 0x65)
            self.deselect()
            r = self.cmd(41, 0x4000_0000, 0x77) if r55 <= 1 else self.cmd(1, 0x4000_0000)
            self.deselect()
            if r == 0:
                break
        if self.cmd(58, 0, 0xFD) == 0:
            self.read(4)
        self.deselect()
        self.cmd(16, 512)
        self.deselect()

    def read_block(self, addr):
        """SdCard::read_block (token wait, 512 bytes, CRC)."""
        if self.cmd(17, addr) != 0:
            self.deselect()
            return None
        for _ in range(8):
            if self.xfer(0xFF) == 0xFE:
                break
        else:
            self.deselect()
            return None
        data = self.read(SECTOR)
        self.read(2)
        self.deselect()
        return data

    def write_block(self, addr, data):
        """SdCard::write_block up to the busy wait."""
        if self.cmd(24, addr) != 0:
            self.deselect()
            return None
        self.xfer(0xFF)
        self.xfer(0xFE)
        for b in data:
            self.xfer(b)
        self.read(2)
        resp = self.xfer(0xFF)
        for _ in range(8):
            if self.xfer(0xFF) == 0xFF:
                break
        self.deselect()
        return resp

    def finish(self, expect_sectors=()):
        self._flush()
        c = self.card
        for lba in expect_sectors:
            self.lines.append(f"expect-sector {lba} {c.get_sector(lba).hex()}")
        self.lines.append("expect-commands " + ",".join(f"{cmd}:{arg:x}" for cmd, arg in c.commands))
        self.lines.append(f"expect-violations {len(c.violations)}")
        self.lines.append(f"expect-idle-clocks {c.idle_clocks}")
        return "\n".join(self.lines) + "\n"


def pattern(seed):
    return bytes((seed * 7 + i * 13) & 0xFF for i in range(SECTOR))


def sdhc_read_write():
    h = Recorder("sdhc_read_write")
    h.sector(1, pattern(1))
    h.init()
    h.read_block(1)
    h.write_block(3, pattern(3))
    h.read_block(3)
    h.read_block(0x20 << 9)  # forgiving: a byte address >= 0x10000
    h.cmd(24, 7)
    h.deselect()  # CS rises while the card waits for the data token
    h.cmd(8, 0x1AA)  # answer not read to the end...
    h.deselect()
    h.cmd(55, 0)  # ...so this command is lost
    h.deselect()
    h.cs(True)
    h.xfer(0x51)  # partial command dropped by CS
    h.xfer(0)
    h.deselect()
    h.cmd(56, 0)  # unknown: no answer
    h.deselect()
    return h.finish(expect_sectors=[3, 7])


def sdsc_strict():
    h = Recorder("sdsc_strict", sdhc=False, strict=True)
    h.sector(2, pattern(2))
    h.cs(True)  # no power-up clocks with CS high
    h.cmd(0, 0)
    h.deselect()
    h.init()
    h.read_block(2 << 9)
    h.read_block(2)  # a block address: violation
    h.write_block(5 << 9, pattern(5))
    return h.finish(expect_sectors=[5])


def faults():
    h = Recorder("faults", mute_cmds=[8], never_ready=True, read_error=True, write_reject=True)
    h.init()
    h.read_block(0)
    h.write_block(4, pattern(4))
    return h.finish(expect_sectors=[4])


def bad_sector():
    h = Recorder("bad_sector", bad_sectors=[5])
    for lba in (4, 5, 6):
        h.sector(lba, pattern(lba))
    h.init()
    for lba in (4, 5, 6):
        h.read_block(lba)
    return h.finish()


def mute_cmd55():
    """CMD55 unanswered: SdCard::init()'s CMD1 fallback"""
    h = Recorder("mute_cmd55", mute_cmds=[55])
    h.init()
    return h.finish()


def mute_cmd0():
    h = Recorder("mute_cmd0", mute_cmds=[0])
    h.init()
    return h.finish()


SLOW_HZ = 391_304  # 18 MHz / 46: the SPI master's reset divider
FAST_HZ = 3_000_000  # 18 MHz / 6: SdCard::init()'s divider after init


def sclk_switch():
    """Fast SCLK only once the card is ready; then a re-init that forgets to slow down."""
    h = Recorder("sclk_switch", strict=True)
    h.sector(1, pattern(1))
    h.sclk(SLOW_HZ)
    h.init()
    h.sclk(FAST_HZ)
    h.read_block(1)
    h.write_block(2, pattern(2))
    h.init()  # CMD0 at 3 MHz: one violation for this whole init
    h.read_block(2)
    return h.finish(expect_sectors=[2])


def sclk_fast_power_up():
    """Fast from power-up: one violation, however long the card stays not ready."""
    h = Recorder("sclk_fast_power_up", strict=True, never_ready=True)
    h.sclk(FAST_HZ)
    h.init()
    return h.finish()


def linux_init():
    """Linux's mmc_core over mmc_spi (SD, SPI mode): the identification and the setup of
    the card, its registers' data blocks, the CRC turned on, the status poll."""
    h = Recorder("linux_init")
    h.sector(16383, pattern(9))  # an 8 MB card: C_SIZE 15
    h.deselect()
    for _ in range(10):
        h.xfer(0xFF)
    h.cmd_crc(0, 0)
    h.deselect()
    if h.cmd_crc(8, 0x1AA) == 0x01:
        h.read(4)
    h.deselect()
    h.cmd_crc(5, 0)  # SDIO probe: no answer
    h.deselect()
    h.cmd_crc(58, 0)
    h.read(4)
    h.deselect()
    for _ in range(3):
        h.cmd_crc(55, 0)
        h.deselect()
        r = h.cmd_crc(41, 0x4000_0000)
        h.deselect()
        if r == 0:
            break
    h.cmd_crc(58, 0)
    h.read(4)
    h.deselect()
    if h.cmd_crc(10, 0) == 0:
        h.data(16)  # CID
    h.deselect()
    h.cmd_crc(59, 1)
    h.deselect()
    if h.cmd_crc(9, 0) == 0:
        h.data(16)  # CSD
    h.deselect()
    h.cmd_crc(55, 0)
    h.deselect()
    if h.cmd_crc(51, 0) == 0:
        h.data(8)  # SCR
    h.deselect()
    h.cmd_crc(55, 0)
    h.deselect()
    if h.cmd_crc(13, 0) == 0:
        h.read(1)  # R2's second byte
        h.data(64)  # SD status
    h.deselect()
    h.cmd_crc(13, 0)  # SEND_STATUS (also the 1 s card-detect poll)
    h.read(1)
    h.deselect()
    return h.finish()


def multi_block_read():
    """CMD18 as Linux's mmc_spi reads it: CS raised after each block (the SPI core ends the
    block's message so) and lowered for the next, then CMD12 sent while the card streams;
    then a CMD18 that a CS pulse with bytes clocked doesn't end, but another command does."""
    h = Recorder("multi_block_read", strict=True)
    for lba in range(10, 14):
        h.sector(lba, pattern(lba))
    h.deselect()
    for _ in range(10):
        h.xfer(0xFF)
    h.init()
    h.cmd_crc(18, 10)
    for _ in range(3):
        h.data(SECTOR)
        h.cs(False)
        h.cs(True)
    for b in bytes([0x40 | 12, 0, 0, 0, 0]):
        h.xfer(b)
    h.xfer(crc7(bytes([0x4C, 0, 0, 0, 0])) << 1 | 1)
    h.read(4)  # stuff byte, R1, not busy
    h.deselect()
    h.cmd_crc(18, 12)
    h.data(SECTOR)
    h.read(5)  # into the next block
    h.deselect()  # CS high, a byte clocked: the card sends nothing and keeps its place
    h.cs(True)
    h.read(SECTOR - 4)  # the rest of the block
    h.cmd_crc(13, 0)  # not CMD12: ends the stream, answered (R2)
    h.read(1)
    h.deselect()
    return h.finish()


def multi_block_write():
    """CMD25: blocks with token FC, the stop token FD; then CMD24, with CRC on and off."""
    h = Recorder("multi_block_write", strict=True)
    h.deselect()
    for _ in range(10):
        h.xfer(0xFF)
    h.init()
    h.cmd_crc(25, 20)
    h.write_blocks(0xFC, [pattern(20), pattern(21), pattern(22)])
    h.xfer(0xFD)
    h.read(4)  # N(BR), busy, not busy
    h.deselect()
    h.cmd_crc(59, 1)
    h.deselect()
    h.cmd_crc(25, 30)
    h.write_blocks(0xFC, [pattern(30)])
    h.write_blocks(0xFC, [pattern(31)], crc_ok=False)  # refused: 0B
    h.xfer(0xFD)
    h.read(4)
    h.deselect()
    h.cmd_crc(24, 40)
    h.write_blocks(0xFE, [pattern(40)], crc_ok=False)
    h.deselect()
    h.cmd(13, 0, 0xFF)  # a wrong CRC7 with CRC on: a violation (strict)
    h.read(1)
    h.deselect()
    h.cmd_crc(59, 0)
    h.deselect()
    h.cmd_crc(24, 41)
    h.write_blocks(0xFE, [pattern(41)], crc_ok=False)  # CRC off: written
    h.deselect()
    return h.finish(expect_sectors=[20, 21, 22, 23, 30, 31, 40, 41])


SCENARIOS = {
    f.__name__: f
    for f in (
        sdhc_read_write,
        sdsc_strict,
        faults,
        bad_sector,
        mute_cmd55,
        mute_cmd0,
        sclk_switch,
        sclk_fast_power_up,
        linux_init,
        multi_block_read,
        multi_block_write,
    )
}


@pytest.mark.parametrize("name", SCENARIOS)
def test_transcript(name):
    text = SCENARIOS[name]()
    path = os.path.join(DIR, f"{name}.txt")
    if os.environ.get("SD_TRANSCRIPTS_UPDATE"):
        with open(path, "w") as f:
            f.write(text)
    assert os.path.exists(path), f"{path} missing; run with SD_TRANSCRIPTS_UPDATE=1"
    with open(path) as f:
        assert f.read() == text, f"{name}: the Python SD card no longer matches {path}"
